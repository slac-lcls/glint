"""Extends analyze_subsample_geometry.py's min_sv finding across the multi-NA deconfound
(subsample_streaks_multi_na.py, results_subsample_multi.jsonl): is the min_sv sign-flip
(well-spread G-directions HURT success at n_target=4 but HELP at n_target=11) specific to
NA=0.028's cone geometry, or does the same pattern hold across distinct NA classes? If it holds
everywhere, that's evidence for a general search-mechanism effect (basin sharpness vs
discoverability, see analyze_subsample_geometry.py's docstring) rather than a fluke of one
geometry. If it doesn't, the mechanism is NA-dependent and the story is more complicated.

  python analyze_subsample_geometry_multi.py
"""
import json
import os
import sys

import numpy as np
import scipy.stats as st

sys.path.insert(0, "..")
from cbxd_sweep import set_NA
from generate_dataset_grid import get_orientation_pool
from subsample_streaks_na028 import NOISE
from subsample_streaks_multi_na import NA_LIST, N_TARGETS
from tangent_validate import _simulate_grouped
from analyze_subsample_geometry import geometry_features, kept_G

LOG = os.path.join(os.path.dirname(__file__), "results_subsample_multi.jsonl")


def run():
    if not os.path.exists(LOG):
        print(f"{LOG} doesn't exist yet -- run subsample_streaks_multi_na.py first")
        return

    by_key = {}
    for line in open(LOG):
        r = json.loads(line)
        by_key.setdefault((r["na"], r["n_target"], r["i"], r["arm"]), r["frac"])

    summary_rows = []
    for na in NA_LIST:
        set_NA(na)
        Rts = get_orientation_pool(na)
        for n_target in N_TARGETS:
            rows = []
            for i, Rt in enumerate(Rts):
                # na=0.028 was migrated from the single-NA script (subsample_streaks_na028.py),
                # which used seed=10_000*n_target+i with NO na-offset -- must match here or the
                # recomputed geometry corresponds to a DIFFERENT random subsample than the one
                # actually tested. Every other NA was generated by subsample_streaks_multi_na.py
                # itself, which does include the na-offset.
                if na == 0.028:
                    seed = 10_000 * n_target + i
                else:
                    seed = int(round(na * 100_000)) + 10_000 * n_target + i
                if (na, n_target, i, "PTS") not in by_key:
                    continue                                # cell not finished yet
                feat = geometry_features(kept_G(Rt, n_target, seed))
                feat.update(i=i, pts=by_key.get((na, n_target, i, "PTS"), np.nan),
                           tan=by_key.get((na, n_target, i, "TAN"), np.nan))
                rows.append(feat)

            if len(rows) < 10:
                print(f"na={na} n_target={n_target}: only {len(rows)}/20 done, skipping stats")
                continue

            pts_arr = np.array([r["pts"] for r in rows])
            tan_arr = np.array([r["tan"] for r in rows])
            minsv_arr = np.array([r["min_sv"] for r in rows])
            rp = st.spearmanr(minsv_arr, pts_arr)
            rt = st.spearmanr(minsv_arr, tan_arr)
            summary_rows.append((na, n_target, len(rows), rp.statistic, rp.pvalue,
                                 rt.statistic, rt.pvalue))
            print(f"na={na:.3f} n_target={n_target:2d} (n={len(rows):2d})  "
                  f"min_sv vs PTS: rho={rp.statistic:+.3f} p={rp.pvalue:.3f}   "
                  f"min_sv vs TAN: rho={rt.statistic:+.3f} p={rt.pvalue:.3f}")

    print()
    print("Sign pattern check (does min_sv correlation flip from n_target=4 to n_target=11, "
          "consistently across NA classes?):")
    by_na = {}
    for na, nt, n, rp, pp, rt, pt in summary_rows:
        by_na.setdefault(na, {})[nt] = (rp, pp)
    for na, d in by_na.items():
        if 4 in d and 11 in d:
            r4, p4 = d[4]
            r11, p11 = d[11]
            flip = "FLIPS" if (r4 * r11 < 0) else "same sign"
            print(f"  NA={na:.3f}: n=4 rho={r4:+.3f} (p={p4:.3f})  ->  n=11 rho={r11:+.3f} "
                  f"(p={p11:.3f})   [{flip}]")


if __name__ == "__main__":
    run()
