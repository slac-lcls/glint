"""Parameterized indexing-ambiguity sim (frontier sweep). Tetragonal, true Laue 4/m, lattice 4/mmm ->
merohedral ambiguity op (k,h,-l). Env knobs: RHO (pseudo-symmetry = intensity corr between the two modes,
1.0 => no teeth), NREF (spots/frame = thin-Ewald sparsity), NOISE (mult), NFRAMES, SEED. Writes
sim_scrambled.stream + truth.npz; prints a machine-parseable SIM line (naive & oracle CC-to-truth)."""
import os, numpy as np
RHO = float(os.environ.get("RHO", "0.0")); NREF = int(os.environ.get("NREF", "120"))
NOISE = float(os.environ.get("NOISE", "1.0")); NFRAMES = int(os.environ.get("NFRAMES", "800"))
rng = np.random.default_rng(int(os.environ.get("SEED", "7")))
A, C = 60.0, 40.0
B = np.array([[1/A, 0, 0], [0, 1/A, 0], [0, 0, 1/C]]).T
DMIN = 3.0; gmax = 1.0 / DMIN; LAM = 1.0; k0 = np.array([0.0, 0.0, 1.0 / LAM]); SMAX = 0.03
OUT = "sim_scrambled.stream"

hmax = int(np.ceil(gmax * A)) + 1; lmax = int(np.ceil(gmax * C)) + 1
hkl = [(h, k, l) for h in range(-hmax, hmax + 1) for k in range(-hmax, hmax + 1)
       for l in range(-lmax, lmax + 1) if (h or k or l)]
hkl = np.array([t for t in hkl if np.linalg.norm(B @ np.array(t)) <= gmax], dtype=int)
Gall = (B @ hkl.T).T
def laue4m(t):
    h, k, l = t
    return max([(h,k,l),(-k,h,l),(-h,-k,l),(k,-h,l),(-h,-k,-l),(k,-h,-l),(h,k,-l),(-k,h,-l)])
OP = lambda h, k, l: (k, h, -l)

# ground-truth intensities, with correlation RHO between OP-related orbit pairs (RHO=1 => true 4/mmm)
Itrue = {}
for t in map(tuple, hkl):
    c = laue4m(t)
    if c in Itrue: continue
    cp = laue4m(OP(*c))
    if cp == c:
        Itrue[c] = 100.0 * np.exp(rng.normal())
    else:
        z1 = rng.normal(); z2 = RHO * z1 + np.sqrt(max(1 - RHO*RHO, 0.0)) * rng.normal()
        Itrue[c] = 100.0 * np.exp(z1); Itrue[cp] = 100.0 * np.exp(z2)
def I_of(t): return Itrue[laue4m(tuple(t))]

def rand_rot():
    q, _ = np.linalg.qr(rng.standard_normal((3, 3)))
    if np.linalg.det(q) < 0: q[:, 0] = -q[:, 0]
    return q

hdr = ("CrystFEL stream format 2.3\nGenerated by sim_ambig\n----- Begin geometry file -----\n"
       "clen = 0.1\nres = 5000\nadu_per_photon = 1\nphoton_energy = 12398.0\n"
       "p0/min_fs = 0\np0/max_fs = 1023\np0/min_ss = 0\np0/max_ss = 1023\n"
       "p0/corner_x = -512\np0/corner_y = -512\np0/fs = x\np0/ss = y\n----- End geometry file -----\n")
asx, bsy, csz = 10.0 / A, 10.0 / A, 10.0 / C
cellblock = (f"Cell parameters {A/10:.5f} {A/10:.5f} {C/10:.5f} nm, 90.000 90.000 90.000 deg\n"
             f"astar = +{asx:.7f} +0.0000000 +0.0000000 nm^-1\nbstar = +0.0000000 +{bsy:.7f} +0.0000000 nm^-1\n"
             f"cstar = +0.0000000 +0.0000000 +{csz:.7f} nm^-1\nlattice_type = tetragonal\ncentering = P\n"
             "unique_axis = c\nprofile_radius = 0.00100 nm^-1\n")

modes = np.zeros(NFRAMES, dtype=int)
from collections import defaultdict
acc_naive = defaultdict(lambda: [0.0, 0]); acc_orac = defaultdict(lambda: [0.0, 0])
with open(OUT, "w") as f:
    f.write(hdr)
    for fr in range(NFRAMES):
        R = rand_rot(); glab = Gall @ R.T
        s = np.linalg.norm(k0[None, :] + glab, axis=1) - 1.0 / LAM
        order = np.argsort(np.abs(s)); sel = order[np.abs(s[order]) < SMAX][:NREF]
        if len(sel) < 8: sel = order[:8]
        m = int(rng.integers(0, 2)); modes[fr] = m; scale = float(rng.lognormal(0.0, 0.3))
        f.write("----- Begin chunk -----\nImage filename: sim.cxi\nEvent: //%d\nImage serial number: %d\n"
                "hit = 1\nindexed_by = file\nphoton_energy_eV = 12398.00\nbeam_divergence = 0.00e+00 rad\n"
                "beam_bandwidth = 1.00e-08 %%\naverage_camera_length = 0.100000 m\nnum_peaks = 0\n"
                "num_saturated_peaks = 0\nPeaks from peak search\n  fs/px   ss/px (1/d)/nm^-1   Intensity  Panel\n"
                "End of peak list\n--- Begin crystal\n" % (fr, fr + 1))
        f.write(cellblock)
        f.write("diffraction_resolution_limit = %.2f nm^-1 or %.2f A\nnum_reflections = %d\n"
                "num_saturated_reflections = 0\nnum_implausible_reflections = 0\nReflections measured after indexing\n"
                "   h    k    l          I   sigma(I)   peak  background  fs/px  ss/px panel\n"
                % (gmax * 10, DMIN, len(sel)))
        for i in sel:
            t = tuple(int(x) for x in hkl[i]); It = I_of(t); meas = scale * It
            sig = NOISE * (0.06 * meas + 8.0); meas = meas + float(rng.normal(0.0, sig))
            h, k, l = OP(*t) if m == 1 else t
            fs, ss = float(rng.uniform(0, 1024)), float(rng.uniform(0, 1024))
            f.write("%4d%5d%5d%11.2f%10.2f%7.1f%11.2f%7.1f%7.1f p0\n" % (h, k, l, meas, sig, meas, 0.0, fs, ss))
            cw = laue4m((h, k, l)); acc_naive[cw][0] += meas; acc_naive[cw][1] += 1
            ct = laue4m(t); acc_orac[ct][0] += meas; acc_orac[ct][1] += 1
        f.write("End of reflections\n--- End crystal\n----- End chunk -----\n")
np.savez("truth.npz", keys=np.array(list(Itrue.keys())), vals=np.array(list(Itrue.values())), modes=modes)

def ccT(acc):
    xs = [ssum / n for c, (ssum, n) in acc.items() if n and c in Itrue]
    ys = [Itrue[c] for c, (ssum, n) in acc.items() if n and c in Itrue]
    return np.corrcoef(xs, ys)[0, 1] if len(xs) > 2 else float("nan")
print("SIM rho=%.2f nref=%d noise=%.1f nfr=%d | naive_ccT=%.3f oracle_ccT=%.3f"
      % (RHO, NREF, NOISE, NFRAMES, ccT(acc_naive), ccT(acc_orac)))
