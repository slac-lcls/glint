"""Pure-python tests for the MPI sharding + stream merge -- no psana, no MPI, no GPU, no glint import,
so they run in CI on a bare interpreter (the psana geometry stays behind the real-data gate).

    python test_shard.py

Covers the two things the MPI wrapper adds on top of the (separately tested) single-process body:
  1. round-robin event ownership is a disjoint + complete + balanced partition of the events, and
  2. concat_streams merges partial streams into one header + all chunks, tolerating empty shards.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import xtc_core
import glint_xtc_mpi   # module import needs no mpi4py (that import lives inside main())

HEADER = "CrystFEL stream format 2.3\nGenerated by GLINT (fftindex)\n"
CHUNK = glint_xtc_mpi.CHUNK_START


def _chunk(event, indexed):
    tag = "glint" if indexed else "none"
    return f"{CHUNK}\nImage filename: xtc://exp_r1\nEvent: //{event}\nindexed_by = {tag}\n----- End chunk -----\n"


def _fake_stream(path, events, indexed):
    with open(path, "w") as f:
        f.write(HEADER)
        for e, ix in zip(events, indexed):
            f.write(_chunk(e, ix))


def test_shard_partition():
    N = 1000
    for nranks in (1, 2, 3, 4, 5, 8, 13, 64):
        owned = [set(i for i in range(N) if xtc_core.event_in_shard(i, r, nranks)) for r in range(nranks)]
        union = set().union(*owned)
        assert union == set(range(N)), f"nranks={nranks}: events not all owned ({len(union)}/{N})"
        for a in range(nranks):
            for b in range(a + 1, nranks):
                assert not (owned[a] & owned[b]), f"nranks={nranks}: rank {a}/{b} overlap"
        sizes = [len(o) for o in owned]
        assert max(sizes) - min(sizes) <= 1, f"nranks={nranks}: imbalance {min(sizes)}..{max(sizes)}"
    # nranks==1 owns everything (single-process behaviour unchanged)
    assert all(xtc_core.event_in_shard(i, 0, 1) for i in range(100))
    print("  PASS shard partition: disjoint + complete + balanced (nranks 1..64)")


def test_concat(tmp="_shard_test_parts"):
    os.makedirs(tmp, exist_ok=True)
    # rank 0: two chunks (one indexed), rank 1: EMPTY shard (header only), rank 2: three chunks (two indexed)
    p0, p1, p2 = (os.path.join(tmp, f"r{i}.stream") for i in range(3))
    _fake_stream(p0, [0, 3], [True, False])
    _fake_stream(p1, [], [])
    _fake_stream(p2, [1, 4, 7], [True, True, False])
    out = os.path.join(tmp, "merged.stream")
    merged = glint_xtc_mpi.concat_streams([p0, p1, p2], out)

    text = open(out).read()
    assert merged == 5, f"expected 5 chunks merged, got {merged}"
    assert text.count(HEADER) == 1, "header must appear exactly once"
    assert text.startswith(HEADER), "merged stream must start with the header"
    assert text.count(CHUNK) == 5, "all 5 chunks must survive the merge"
    assert text.count("indexed_by = glint") == 3, "the 3 indexed chunks must survive"
    # global event ids preserved, no collision across ranks
    for e in (0, 3, 1, 4, 7):
        assert f"Event: //{e}\n" in text, f"event {e} missing from merge"

    # all-empty case still yields a single valid header
    e0, e1 = (os.path.join(tmp, f"e{i}.stream") for i in range(2))
    _fake_stream(e0, [], []); _fake_stream(e1, [], [])
    out_e = os.path.join(tmp, "empty.stream")
    m = glint_xtc_mpi.concat_streams([e0, e1], out_e)
    et = open(out_e).read()
    assert m == 0 and et.count(HEADER) == 1 and CHUNK not in et, "empty merge must be header-only"

    for f in (p0, p1, p2, out, e0, e1, out_e):
        os.remove(f)
    os.rmdir(tmp)
    print("  PASS concat: header-once, all chunks (incl. empty shards), global ids preserved")


if __name__ == "__main__":
    test_shard_partition()
    test_concat()
    print("ALL PASS")
